'use strict';
const assert = require('node:assert/strict');
const {run, ZayronError} = require('../web/engine.js');
const out = code => run(code).output;
assert.deepEqual(out('ورّني "يا هلا بالعالم"؛'), ['يا هلا بالعالم']);
assert.deepEqual(out('خل س يكون ١٠؛ س يصير س + ٢؛ ورني س * ٣؛'), ['36']);
assert.deepEqual(out('خل النتيجة يكون ٨؛ لو النتيجة أكبر من ٥ { ورني "كفو"؛ } غير كذا { ورني "حاول"؛ }'), ['كفو']);
assert.deepEqual(out('خل ن يكون ١؛ دام ن <= ٣ { ورني ن؛ ن يصير ن + ١؛ }'), ['1','2','3']);
assert.deepEqual(out('لف ٣ مرات { ورني "لفة"، الجولة؛ }'), ['لفة 1','لفة 2','لفة 3']);
assert.deepEqual(out('خل ن يكون ٢؛ لف ن مرات { ن يصير ن + ١؛ ورني الجولة؛ } ورني ن؛'), ['1','2','4']);
assert.deepEqual(out('لف ٢ مرات { لف ٢ مرات { ورني الجولة؛ } ورني الجولة؛ }'), ['1','2','1','1','2','2']);
assert.deepEqual(out('سالفة ضاعف(ن) { رجّع ن * ٢؛ } ورني ضاعف(٥)؛'), ['10']);
assert.deepEqual(out('ورني صح و مو غلط، فاضي، "أ" + "ب"؛'), ['صح فاضي أب']);
assert.deepEqual(out('سالفة عاملي(ن) { لو ن <= ١ { رجع ١؛ } رجع ن * عاملي(ن - ١)؛ } ورني عاملي(٥)؛'), ['120']);
assert.deepEqual(out('سالفة ابحث() { لف ٥ مرات { لو الجولة يساوي ٣ { رجع الجولة؛ } } رجع ٠؛ } ورني ابحث()؛'), ['3']);
for (const code of ['ورني مجهول؛', 'ورني ٢ / ٠؛', 'خل س يكون ١؛ خل س يكون ٢؛', 'ورني "نص؛', 'رجع ١؛', 'ورني الجولة؛', 'لف -١ مرات {}', 'لف ١.٥ مرات {}', 'خل أ يكون ١', 'print("hi");']) assert.throws(() => run(code), ZayronError, code);
assert.throws(() => run('دام صح { }', {maxSteps:100}), /تعدّى الحد/);
assert.throws(() => run('لف ٩٩٩٩٩ مرات { }', {maxSteps:100}), /تعدّى الحد/);
assert.throws(() => run('سالفة لانهائي() { رجع لانهائي()؛ } لانهائي()؛'), /حد استدعاء/);
assert.throws(() => run('ورني ١؛ @'), /السطر/);
console.log('Zayron 0.2 interpreter tests passed');
