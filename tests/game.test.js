'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
require('../web/engine.js');
const {create} = require('../web/game-runtime.js');
const operations = [];
const ctx = {fillRect(...args) { operations.push(['rect',...args]); }, beginPath(){}, arc(...args){ operations.push(['circle',...args]); }, fill(){}, fillText(...args){ operations.push(['text',...args]); }};
const keys = new Set(); let lines = [];
const game = create({context:ctx, keys, random:()=>0.5, onOutput:line=>lines.push(line)});
const source = fs.readFileSync('examples/صيد-النجوم.zyr', 'utf8');
assert.equal(game.initialize(source).animated,true);
game.frame(0.016);
assert(operations.some(op=>op[0]==='circle'));
assert(operations.some(op=>op[0]==='text' && op[1]==='النجوم:'));
let playerX=operations.filter(op=>op[0]==='circle').at(-1)[1];
keys.add('يمين');operations.length=0;game.frame(0.05);
assert(operations.filter(op=>op[0]==='circle').at(-1)[1]>playerX);
const textGame = create({context:ctx, keys, onOutput:l=>lines.push(l)});
assert.equal(textGame.initialize('ورني "هلا"؛').animated,false); assert.equal(lines.at(-1),'هلا');
const invalid = create({context:ctx, keys});assert.throws(()=>invalid.initialize('دائرة(١، ٢، -١، "#ffffff")؛'),/سالب/);
const infinite = create({context:ctx, keys});infinite.initialize('سالفة حدث(زمن) { دام صح { } } وقت_التحديث(حدث)؛');assert.throws(()=>infinite.frame(0.01),/تعدّى الحد/);
console.log('2D runtime tests passed');
